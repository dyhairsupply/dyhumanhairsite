#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
DY Deyu | 生成「双击 index.html 就能看」所需的离线数据快照

浏览器不允许 file:// 页面用 fetch 读取本地 JSON，但允许 <script src="..."> 加载本地 JS。
本脚本把 content/*.json 打包成一个普通 JS 文件，只在 file:// 模式下被加载；
通过 HTTP 访问（本地服务器 / Netlify）时完全不加载它，前台始终读取实时 JSON。

什么时候要重新运行：
  - 在后台 Publish 过内容、或手动改过 content/*.json 之后，
    如果还想用「双击 index.html」的方式看最新内容，就运行一次。

用法：python tools/gen_offline_data.py
"""

import json
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
OUT = CONTENT / "offline-data.js"
FILES = ["site", "ui", "pages", "categories", "products"]


def main():
    data = {}
    for name in FILES:
        path = CONTENT / f"{name}.json"
        data[name] = json.loads(path.read_text(encoding="utf-8"))

    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    # U+2028 / U+2029 在旧版 JS 引擎里会截断字符串字面量
    payload = payload.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    payload = payload.replace("</script", "<\\/script")

    text = (
        "/* AUTO-GENERATED by tools/gen_offline_data.py - DO NOT EDIT BY HAND.\n"
        "   Offline (file://) preview snapshot. HTTP visits read content/*.json directly.\n"
        "   Publish in the CMS or edit JSON, then re-run the generator to refresh this. */\n"
        "window.__DY_OFFLINE_DATA__ = " + payload + ";\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"已生成 {OUT.relative_to(ROOT)}  ({len(text.encode('utf-8')) / 1024:.0f} KB)")
    print("现在双击 index.html 即可离线浏览；HTTP 访问仍读取实时 JSON。")


if __name__ == "__main__":
    main()
